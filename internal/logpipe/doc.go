// Package logpipe 把失败日志变成稳定的指纹。
//
// 六个阶段,每个是可独立测试的纯函数:
//
//	Collect → Redact(粗) → Extract → Redact(细) → Normalize → Fingerprint
//
// 干什么:去 ANSI、定位关键片段、脱敏、洗掉路径/时间戳/PID/地址,
// 算精确指纹与模糊指纹。
//
// 不干什么:不调 LLM(由 test/arch 强制);不做常驻日志管道;
// 不收集成功的日志。
//
// 约束:所有阶段函数必须是纯函数 —— 无包级变量,不读时钟、随机数、
// 环境变量。相同输入必须产生 byte 级相同的输出。指纹不可复现 =
// 知识库永远查不到东西,而且这个故障是静默的。
//
// 规则版本号参与指纹计算。规则一改,用留存的原始日志重算历史。
//
// 允许导入:core、标准库。
